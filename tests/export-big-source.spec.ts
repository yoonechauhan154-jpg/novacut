import { test, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

/**
 * Stage 1 fix #1+#2+#6: big-source export test.
 *
 * Generates (in CI) a 1080p, >=50 MB source with an audio track, creates a project
 * with a split, a zoom transition and a glitch effect layer with a keyframe, uses
 * only 10 seconds of it, exports to MP4, and verifies with ffprobe:
 *   - duration matches timeline
 *   - frames are changing
 *   - audio stream is present and non-silent (volumedetect)
 *
 * The fixture is generated by the CI workflow (build-apk.yml) and committed to
 * test-assets/ only if it fits the 15-minute Playwright budget; otherwise this test
 * is skipped.
 */
test('big source (>=50 MB) with split + zoom + glitch exports with audio', async ({ page }, testInfo) => {
  test.setTimeout(300000);
  await page.goto('/');

  const fixture = resolve('test-assets/big-60s-1080p.mp4');
  let fixtureSize = 0;
  try { fixtureSize = (await import('node:fs')).statSync(fixture).size; } catch { /* fixture may not exist locally */ }
  test.skip(!fixtureSize || fixtureSize < 50 * 1024 * 1024, `big-source fixture missing or <50 MB (found ${fixtureSize} bytes)`);

  const output = await page.evaluate(async (fixturePath: string) => {
    const exporterPath = '/src/export/exportProject.ts';
    const presetsPath = '/src/data/presets.ts';
    const { exportProject } = await import(exporterPath);
    const { createBaseClip } = await import(presetsPath);

    const source = createBaseClip({
      id: 'big-source',
      trackId: 'main-video',
      trackType: 'video',
      title: 'Big Source',
      startTime: 0,
      duration: 10,           // use only 10 seconds of the 60s source
      sourceStart: 20,        // cut from the middle of the source
      sourceEnd: 30,
      sourceType: 'uploaded-video',
      mediaUrl: fixturePath,
      volume: 100,
      muted: false,
      transitionIn: 'none',
    });

    // Split: second clip continues from where the first ends (same source, different range)
    const split = createBaseClip({
      id: 'big-source-split',
      trackId: 'main-video',
      trackType: 'video',
      title: 'Big Source Split',
      startTime: 10,
      duration: 10,           // another 10 seconds -> 20s timeline total
      sourceStart: 30,
      sourceEnd: 40,
      sourceType: 'uploaded-video',
      mediaUrl: fixturePath,
      volume: 100,
      muted: false,
      transitionIn: 'zoom',   // zoom transition between the two clips
    });

    // Glitch effect layer with keyframes (digital glitch slice FX)
    const glitch = createBaseClip({
      id: 'glitch-layer',
      trackId: 'effect-layer',
      trackType: 'effect-layer',
      title: 'Digital Glitch Slice FX',
      startTime: 0,
      duration: 20,           // spans the whole timeline
      sourceType: 'effect-layer',
      effect: 'glitch',
      effectIntensity: 75,
      blendMode: 'screen',
      keyframes: [
        { id: 'kf-1', timeOffset: 0, scale: 1, x: 0, y: 0, rotation: 0, opacity: 1, effectIntensity: 0, easing: 'linear' },
        { id: 'kf-2', timeOffset: 10, scale: 1, x: 0, y: 0, rotation: 0, opacity: 1, effectIntensity: 75, easing: 'linear' },
      ],
    });

    const result = await exportProject(
      { id: 'big-test', name: 'Big Source Test', aspectRatio: '9:16', resolution: '1080p', fps: 30,
        background: { type: 'solid', solidColor: '#000000' },
        clips: [source, split, glitch] },
      'mp4',
      { current: false },
      () => {}
    );

    const base64: string = await new Promise(resolve => {
      const r = new FileReader();
      r.onload = () => resolve(String(r.result).split(',')[1]);
      r.readAsDataURL(result.blob);
    });
    return {
      base64,
      mime: result.blob.type,
      size: result.size,
      duration: result.duration,
      frames: result.frames,
      hasAudio: result.hasAudio,
      audioSkipped: result.audioSkipped,
      verification: result.verification,
    };
  }, fixture);

  expect(output.verification.ok, output.verification.error || '').toBe(true);
  expect(output.frames).toBeGreaterThan(0);
  expect(output.hasAudio).toBe(true);
  expect(output.audioSkipped).toBe(false);
  expect(output.verification.framesChanging).toBe(true);
  expect(output.duration).toBeCloseTo(20, 1); // 10s + 10s = 20s timeline

  mkdirSync('test-exports', { recursive: true });
  const file = resolve('test-exports/big-source-export.mp4');
  writeFileSync(file, Buffer.from(output.base64, 'base64'));

  // ffprobe verification: audio present, non-silent (volumedetect), duration, frames changing
  const probe = JSON.parse(execFileSync('ffprobe', [
    '-v', 'error', '-count_frames', '-show_streams', '-show_format', '-of', 'json', file,
  ], { encoding: 'utf8' }));

  const video = probe.streams.find((s: { codec_type: string }) => s.codec_type === 'video');
  const audio = probe.streams.find((s: { codec_type: string }) => s.codec_type === 'audio');
  expect(video).toBeTruthy();
  expect(audio).toBeTruthy();

  const measuredDuration = Number.isFinite(Number(probe.format.duration))
    ? Number(probe.format.duration)
    : 0;
  expect(measuredDuration).toBeGreaterThan(15);
  expect(measuredDuration).toBeLessThan(30);
  expect(Number(video.nb_read_frames)).toBeGreaterThan(30);

  // volumedetect: audio must be present and non-silent (mean_volume < -50 dB means there is signal)
  const vol = execFileSync('ffmpeg', [
    '-v', 'error', '-i', file, '-af', 'volumedetect', '-f', 'null', '-',
  ], { encoding: 'utf8' });
  const meanVolMatch = vol.match(/mean_volume:\s*([-\d.]+)\s*dB/);
  expect(meanVolMatch).toBeTruthy();
  const meanVolume = Number(meanVolMatch![1]);
  expect(meanVolume).toBeGreaterThan(-60); // not silence

  await testInfo.attach('ffprobe', { body: JSON.stringify(probe, null, 2), contentType: 'application/json' });
  await testInfo.attach('volumedetect', { body: vol, contentType: 'text/plain' });
});

